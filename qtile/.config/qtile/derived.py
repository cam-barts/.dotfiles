"""Render mako and swaylock configs from theme.py tokens.

Both programs read plain config files, so the tokens are written into them. The
target files are stow symlinks into ~/.dotfiles, which keeps the generated
output in git: a token change shows up as a diff in all three files at once.
"""

import subprocess
from pathlib import Path

import theme as t

CONFIG = Path.home() / ".config"
HEADER = "# Generated by ~/.config/qtile/derived.py from theme.py. Edit tokens there.\n"


def _hex(color: str, alpha: str = "") -> str:
    """``#rrggbb`` -> ``rrggbb[aa]`` (swaylock wants no leading ``#``)."""
    return color.lstrip("#") + alpha


def mako_config() -> str:
    """Observatory panel with Night Market urgency borders."""
    return f"""{HEADER}font={t.FONT} 11
background-color={t.PANEL}{t.PANEL_ALPHA}
text-color={t.TXT}
border-color={t.HAIR}
border-size={t.BORDER}
border-radius={t.RADIUS}
padding=12,14
margin={t.GAP}
outer-margin={t.BAR_HEIGHT + t.GAP},{t.GAP}
width=360
max-icon-size=40
default-timeout=6000
layer=overlay
anchor=top-right
format=<b>%s</b>\\n%b

[urgency=low]
border-color={t.CYAN}
text-color={t.MUTED}

[urgency=normal]
border-color={t.AMBER}

[urgency=critical]
border-color={t.MAGENTA}
default-timeout=0
"""


def swaylock_config() -> str:
    """Aurora wallpaper with the orange focal ring."""
    scrim = _hex(t.CANVAS, t.SCRIM_ALPHA)
    clear = "00000000"
    states = {
        "": (t.ORANGE, t.TXT),
        "-clear": (t.FAINT, t.MUTED),
        "-ver": (t.CYAN, t.CYAN),
        "-wrong": (t.MAGENTA, t.MAGENTA),
    }
    lines = [
        f"image=eDP-1:{t.WALLPAPER_DIR}/{t.WALLPAPER_SMALL}",
        f"image={t.WALLPAPER_DIR}/{t.WALLPAPER_LARGE}",
        "scaling=fill",
        f"font={t.FONT}",
        "font-size=22",
        "indicator-radius=90",
        "indicator-thickness=6",
        "show-failed-attempts",
        "ignore-empty-password",
        f"key-hl-color={_hex(t.SORANGE)}",
        f"bs-hl-color={_hex(t.MAGENTA)}",
        f"separator-color={clear}",
    ]
    for state, (ring, text) in states.items():
        lines += [
            f"inside{state}-color={scrim}",
            f"ring{state}-color={_hex(ring)}",
            f"line{state}-color={clear}",
            f"text{state}-color={_hex(text)}",
        ]
    return HEADER + "\n".join(lines) + "\n"


def _write_if_changed(path: Path, text: str) -> bool:
    """Write ``text`` to ``path`` unless it already matches; report a change."""
    try:
        if path.read_text() == text:
            return False
    except FileNotFoundError:
        path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


def write_all() -> None:
    """Regenerate both configs; reload mako if its config changed."""
    if _write_if_changed(CONFIG / "mako" / "config", mako_config()):
        subprocess.run(["makoctl", "reload"], check=False, capture_output=True)
    _write_if_changed(CONFIG / "swaylock" / "config", swaylock_config())


if __name__ == "__main__":
    write_all()
